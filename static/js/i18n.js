/* ---------- Core i18n helpers ---------- */
if (typeof window.$$ !== 'function') {
  window.$$ = function(s) { return Array.from(document.querySelectorAll(s)); };
}
function currentLang() {
  try { return localStorage.getItem('triage.ui.lang') || 'en'; } catch (e) { return 'en'; }
}
function setLang(code) {
  try { localStorage.setItem('triage.ui.lang', code); } catch (e) {}
  applyI18n();
}
function t(key) {
  var lang = currentLang();
  var d = I18N_DICT[lang];
  if (d && d[key] != null) return d[key];
  if (I18N_DICT.en && I18N_DICT.en[key] != null) return I18N_DICT.en[key];
  return key;
}
function targetLangName(code) {
  code = code || currentLang();
  if (I18N_TARGET_NAMES[code]) return I18N_TARGET_NAMES[code];
  var found = I18N_LANGS.filter(function(l) { return l.code === code; })[0];
  return found ? found.native : 'English';
}
/* Replace only text nodes so nested icons/spans survive translation. */
function setNodeText(el, txt) {
  if (!el) return;
  var textNodes = [];
  for (var i = 0; i < el.childNodes.length; i++) {
    var n = el.childNodes[i];
    if (n.nodeType === 3 && n.textContent.replace(/\s+/g, ' ').trim()) textNodes.push(n);
  }
  if (textNodes.length === 1) { textNodes[0].textContent = txt; return; }
  if (!el.children || !el.children.length) { el.textContent = txt; return; }
  el.appendChild(document.createTextNode(' ' + txt));
}
function applyI18n() {
  var lang = currentLang();
  var d = I18N_DICT[lang] || I18N_DICT.en;
  $$('[data-i18n]').forEach(function(el) {
    var key = el.getAttribute('data-i18n');
    var val = d && d[key] != null ? d[key] : (I18N_DICT.en[key] != null ? I18N_DICT.en[key] : null);
    if (val == null) return;
    setNodeText(el, val);
  });
  $$('[data-i18n-html]').forEach(function(el) {
    var key = el.getAttribute('data-i18n-html');
    var val = d && d[key] != null ? d[key] : (I18N_DICT.en[key] != null ? I18N_DICT.en[key] : null);
    if (val == null) return;
    el.innerHTML = val;
  });
  $$('[data-i18n-ph]').forEach(function(el) {
    var key = el.getAttribute('data-i18n-ph');
    var val = d && d[key] != null ? d[key] : (I18N_DICT.en[key] != null ? I18N_DICT.en[key] : null);
    if (val != null) el.setAttribute('placeholder', val);
  });
  document.documentElement.setAttribute('lang', lang);
}
/* Server-side translation via POST /api/translate (LLM). Falls back to original text. */
function translateText(text, target) {
  target = target || currentLang();
  if (!text || target === 'en') return Promise.resolve(text);
  return fetch('/api/translate', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    credentials: 'include',
    body: JSON.stringify({ text: String(text).slice(0, 8000), target: target, target_name: targetLangName(target) })
  }).then(function(r) { return r.ok ? r.json() : null; })
    .then(function(j) { return (j && j.status === 'ok' && j.translated) ? j.translated : text; })
    .catch(function() { return text; });
}
function populateUiLangSelect(sel) {
  if (!sel) return;
  sel.innerHTML = '';
  I18N_LANGS.forEach(function(l) {
    var o = document.createElement('option');
    o.value = l.code;
    o.textContent = l.native + ' (' + l.label + ')';
    sel.appendChild(o);
  });
  sel.value = currentLang();
  sel.addEventListener('change', function() { setLang(sel.value); });
}
